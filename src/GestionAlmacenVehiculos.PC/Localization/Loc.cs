    public string FormatError(Exception ex)
    {
        var code = (ex.Message ?? "").Trim();
        if (code.Length is > 0 and < 64 && !code.Contains(' ') && !code.Contains('\n'))
        {
            var key = "Err_" + code;
            if (Es.ContainsKey(key) || Zh.ContainsKey(key))
                return Get(key);
        }
        return string.IsNullOrWhiteSpace(code) ? Get("Err_generic") : $"{Get("Error")}: {code}";
    }

    public string LocalizeKind(string kind) => kind.ToLowerInvariant() switch
    {
        "park" => Get("KindPark"),
        "unpark" => Get("KindUnpark"),
        "login" => Get("KindLogin"),
        "logout" => Get("KindLogout"),
        "warehouse" => Get("KindWarehouse"),
        "material" => Get("KindMaterial"),
        "location" => Get("KindLocation"),
        _ => kind,
    };
